import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { tmpdir } from 'node:os';
import { format } from 'prettier';
import { emailMedia } from './email-media-manifest.mjs';

const root = process.argv[2];
if (!root)
  throw new Error('Usage: node scripts/import-email-media.mjs /path/to/memento-materiale-email');
const output = resolve('public/images/servizi');
const temporary = mkdtempSync(join(tmpdir(), 'memento-email-'));
mkdirSync(output, { recursive: true });
const groups = {};
for (const [group, name, relative, title, location, alt, settings = {}] of emailMedia) {
  let source = resolve(root, relative);
  const slug = `email-${name}`;
  if (settings.pdf || settings.rotate) {
    const converted = join(temporary, `${slug}.png`);
    execFileSync('sips', [
      ...(settings.rotate ? ['-r', String(settings.rotate)] : []),
      '-s',
      'format',
      'png',
      source,
      '--out',
      converted,
    ]);
    source = converted;
  }
  const info = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', source], {
    encoding: 'utf8',
  });
  const originalWidth = Number(info.match(/pixelWidth: (\d+)/)[1]);
  const originalHeight = Number(info.match(/pixelHeight: (\d+)/)[1]);
  const width = Math.min(1920, originalWidth);
  // Match cwebp's rounding when the target height is inferred with -resize WIDTH 0.
  const height = Math.ceil((originalHeight * width) / originalWidth);
  const widths = [...new Set([Math.min(640, width), Math.min(1200, width), width])];
  for (const size of widths) {
    execFileSync('cwebp', [
      '-quiet',
      '-q',
      '82',
      '-m',
      '6',
      '-resize',
      String(size),
      '0',
      source,
      '-o',
      join(output, `${slug}-${size}.webp`),
    ]);
  }
  (groups[group] ??= []).push({
    slug,
    title,
    location,
    alt,
    width,
    height,
    widths,
    ...(settings.contain ? { contain: true } : {}),
    ...(settings.objectPosition ? { objectPosition: settings.objectPosition } : {}),
  });
  console.log(`${slug}: ${widths.join('/')}px`);
}
const generated = `// Generated by scripts/import-email-media.mjs; sources and captions: scripts/email-media-manifest.mjs.\nimport type { ServicePhoto } from './service-media';\n\nexport const emailPhotos = ${JSON.stringify(groups)} satisfies Record<string, readonly ServicePhoto[]>;\n`;
writeFileSync(
  'src/app/core/email-photos.generated.ts',
  await format(generated, { parser: 'typescript', singleQuote: true, printWidth: 100 }),
);
console.log(`Imported ${emailMedia.length} images. Originals left in place.`);
